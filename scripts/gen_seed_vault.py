def quote(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(note: dict) -> str:
    lines = ["---", f"id: {note['id']}", f"title: {quote(note['title'])}"]

    def block(key: str, items: list) -> None:
        if not items:
            lines.append(f"{key}: []")
            return
        lines.append(f"{key}:")
        for item in items:
            lines.append(f"  - {quote(item)}")

    block("aliases", note["aliases"])
    block("tags", note["tags"])
    block("projects", note["projects"])
    lines.append("sources:")
    lines.append('  - "seed:v0.2"')
    lines.append("created: 2026-11-12")
    block("prerequisite", note["prerequisite"])
    block("related", note["related"])
    block("part_of", note["part_of"])
    block("keywords", note["keywords"])
    block("questions", note["questions"])
    lines.append(f"outline: {quote(note['outline'])}")
    block("match", note["match"])
    lines.append("fallback: true" if note.get("fallback") else "fallback: false")
    lines.append("---")
    lines.append("")
    lines.append(note["body"].strip())
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    POINTS.mkdir(parents=True, exist_ok=True)
    for note in NOTES:
        path = POINTS / f"{note['id']}.md"
        path.write_text(render(note), encoding="utf-8")
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
